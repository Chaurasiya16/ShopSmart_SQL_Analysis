/* Business Question 1 :"Show me each order with the customer's name,
 the product purchased, the quantity, and the order status." */
SELECT O.Order_ID ,
       C.Customer_Name ,
       P.Product_Name, 
       O.Quantity, 
       O.Order_Status
FROM Orders O 
JOIN Customers C 
    ON O.Customer_ID = C.Customer_ID
JOIN Products P 
    ON O.Product_ID = P.Product_ID
ORDER BY O.Order_ID;

/*Business Question 2:Which products generate the most revenue? */
SELECT 
   P.Product_Name,
SUM(O.Quantity * P.Price) AS Total_Revenue
FROM Orders O 
JOIN Products P 
  ON P.Product_ID = O.Product_ID
WHERE O.Order_Status = 'Delivered'
GROUP BY P.Product_Name
ORDER BY Total_Revenue DESC;

/*Business Question 3:which cities generate the most revenue from delivered orders. */
SELECT 
   C.City,
SUM(O.Quantity * P.Price) AS Total_Revenue
FROM Orders O 
JOIN Customers C
  ON O.Customer_ID = C.Customer_ID
JOIN Products P 
  ON O.Product_ID = P.Product_ID
WHERE O.Order_Status = 'Delivered'
GROUP BY C.City
ORDER BY Total_Revenue DESC;

/*Business Question 4:how many orders are Delivered, Pending, and Cancelled. */
SELECT Order_Status, COUNT(*) AS Total_Orders
FROM Orders
GROUP BY Order_Status
ORDER BY Total_Orders DESC;

/*Business Question 5 :compare revenue across May and June 2026 to
 determine which month performed better. */
SELECT MONTHNAME(O.Order_Date) AS Order_Month,
	   SUM(O.Quantity * P.Price) AS Total_Revenue
FROM Orders O 
JOIN Products P 
     ON P.Product_ID = O.Product_ID 
WHERE O.Order_Status = 'Delivered'
GROUP BY 
         MONTH(O.Order_Date),
         MONTHNAME(O.Order_Date)
ORDER BY MONTH(O.Order_Date) DESC;

/*Business Question 6 : count delivered orders in each month.*/
SELECT
    MONTHNAME(Order_Date) AS Order_Month,
    COUNT(*) AS Total_Orders
FROM Orders 
WHERE Order_Status = 'Delivered'
GROUP BY MONTH(Order_Date), MONTHNAME(Order_Date)
ORDER BY MONTH(Order_Date);

/*Business Question 7 :compare the revenue generated by each product in May and June. */
SELECT 
    MONTHNAME(O.Order_Date) AS Order_Month,
    P.Product_Name,
    SUM(O.Quantity) AS Total_Quantity,
    SUM(O.Quantity * P.Price) AS Total_Revenue
FROM Orders O 
JOIN Products P
    ON O.Product_ID = P.Product_ID
WHERE O.Order_Status = 'Delivered'
GROUP BY
    MONTH(O.Order_Date),
    MONTHNAME(O.Order_Date),
    P.Product_Name
ORDER BY
    MONTH(O.Order_Date),
    Total_Revenue DESC;

/*Business Question 8:Find the top customer  */
SELECT 
   C.Customer_Name,
SUM(O.Quantity * P.Price) AS Total_Revenue
FROM Orders O 
JOIN Customers C
  ON O.Customer_ID = C.Customer_ID
JOIN Products P 
  ON O.Product_ID = P.Product_ID
WHERE O.Order_Status = 'Delivered'
GROUP BY C.Customer_Name
ORDER BY Total_Revenue DESC
LIMIT 1;

/* Business Question 9 :how many orders are still pending or have been cancelled. */
SELECT Order_Status, COUNT(*) AS Total_Orders
FROM Orders
WHERE Order_Status IN ('Pending', 'Cancelled')
GROUP BY Order_Status
ORDER BY Total_Orders DESC;
